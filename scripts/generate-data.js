/*
 * Builds database/seed.sql from the shared sample data.
 *
 *   npm run data:generate     writes database/seed.sql
 *   npm run db:setup          builds the same SQL and loads it straight into MySQL
 */
const fs = require('fs');
const path = require('path');
const bcrypt = require('bcryptjs');
const { generate } = require('../public/js/lib/sample-data.js');

function sqlValue(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  const m = /^([dnD]):(-?\d+)$/.exec(v);
  if (m) {
    const n = +m[2];
    if (m[1] === 'D') return `DATE_ADD(CURDATE(), INTERVAL ${n} DAY)`;
    if (m[1] === 'd') return `TIMESTAMPADD(MINUTE, ${n}, CURDATE())`;
    return `TIMESTAMPADD(MINUTE, ${n}, NOW())`;
  }
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}
function insert(table, cols, rows) {
  if (!rows.length) return '';
  const lines = rows.map((r) => `  (${cols.map((c) => sqlValue(r[c])).join(', ')})`);
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${lines.join(',\n')};\n\n`;
}

function buildSql() {
  const { sites, hauliers, drivers, vehicles, users, loads, tickets, stockpiles, documents, issues } = generate();
  const passwordHash = bcrypt.hashSync('demo1234', 10);
  users.forEach((u) => { u.password_hash = passwordHash; });
  let sql = `-- HaulDesk sample data. Everything here is fictitious.\n-- Generated by scripts/generate-data.js. Dates are relative to the day you import it.\nUSE hauldesk;\n\n`;
  sql += insert('sites', ['id', 'code', 'name', 'site_type', 'division', 'lat', 'lng'], sites);
  sql += insert('hauliers', ['id', 'name', 'contact_name', 'phone', 'email'], hauliers);
  sql += insert('drivers', ['id', 'full_name', 'haulier_id', 'phone', 'licence_no', 'licence_expiry', 'prdp_expiry', 'active'], drivers);
  sql += insert('vehicles', ['id', 'registration', 'haulier_id', 'tracker_provider', 'capacity_t', 'licence_disc_expiry', 'home_site_id', 'active'], vehicles);
  sql += insert('users', ['id', 'username', 'password_hash', 'full_name', 'role', 'division', 'haulier_id', 'driver_id'], users);
  sql += insert('loads', ['id', 'load_no', 'origin_site_id', 'destination_site_id', 'haulier_id', 'vehicle_id', 'driver_id', 'product',
    'planned_tonnes', 'planned_date', 'status', 'loaded_at', 'departed_at', 'delivered_at', 'notes'], loads);
  sql += insert('weighbridge_tickets', ['id', 'ticket_no', 'load_id', 'site_id', 'direction', 'gross_t', 'tare_t', 'weighed_at'], tickets);
  sql += insert('stockpile_readings', ['id', 'site_id', 'product', 'reading_date', 'tonnes'], stockpiles);
  sql += insert('documents', ['id', 'doc_no', 'title', 'category', 'load_id', 'site_id', 'haulier_id', 'storage_ref', 'created_on', 'retain_until'], documents);
  sql += insert('issues', ['id', 'ref', 'title', 'category', 'priority', 'status', 'load_id', 'vehicle_id', 'reported_by', 'description',
    'resolution', 'created_at', 'resolved_at'], issues);
  return { sql, counts: { loads: loads.length, tickets: tickets.length, documents: documents.length, issues: issues.length } };
}

if (require.main === module) {
  const { sql, counts } = buildSql();
  fs.writeFileSync(path.join(__dirname, '..', 'database', 'seed.sql'), sql);
  console.log(`Wrote database/seed.sql: ${counts.loads} loads, ${counts.tickets} weighbridge tickets, ${counts.documents} documents, ${counts.issues} issues.`);
}

module.exports = { buildSql };
